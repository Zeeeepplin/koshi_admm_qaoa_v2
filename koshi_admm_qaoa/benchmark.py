def _prospective_quantum_trial(task):
    """Isolated-process worker; Qiskit's algorithm RNG is process-global."""
    family, reps, seed, primary, fopt = task
    faulted = [primary["contingency"]["forced_open_branch_index"]]
    network = build_full_network()
    qp, meta = build_reconfig_qubo(
        network,
        faulted=faulted,
        **{
            key: primary["qubo_parameters"][key]
            for key in ("lambda_card", "lambda_cycle", "lambda_iso", "loss_bias")
        },
    )
    if family == "qaoa":
        config = primary["qaoa"]
        result = solvers.solve_qaoa(
            qp,
            reps=reps,
            kind="noiseless",
            shots=config["shots"],
            maxiter=config["optimizer_max_iterations"],
            seed=seed,
            optimizer_tol=config["optimizer_tolerance"],
        )
    elif family == "qrao":
        config = primary["qrao"]
        result = solvers.solve_qrao(
            qp,
            max_vars_per_qubit=config["max_variables_per_qubit"],
            maxiter=config["optimizer_max_iterations"],
            shots=config["shots"],
            seed=seed,
            optimizer_tol=config["optimizer_tolerance"],
        )
    else:
        raise ValueError(f"unknown prospective worker family: {family}")
    score = solvers.score_config(network, result["x"], meta, faulted=faulted)
    return (
        _trial(seed, result, score, fopt, network, meta, faulted=faulted),
        int(result["n_qubits"]),
    )


def approx_ratio(fval, fopt):
    """Legacy offset-sensitive objective ratio, retained for comparability."""
    if abs(fopt) < 1e-9:
        return 1.0 if abs(fval - fopt) < 1e-6 else 0.0
    return float(fval / fopt) if fopt < 0 else float(fopt / fval)


def _finite(value):
    if value is None:
        return None
    value = float(value)
    return value if math.isfinite(value) else None


def _jsonable(value):
    if isinstance(value, np.ndarray):
        return [_jsonable(item) for item in value.tolist()]
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return _finite(value)
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, float):
        return _finite(value)
    return value


def _git_commit():
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def _versions():
    names = [
        "numpy", "cvxpy", "networkx", "qiskit", "qiskit-optimization",
        "qiskit-algorithms", "qiskit-aer",
    ]
    result = {}
    for name in names:
        try:
            result[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            result[name] = None
    return result


def _soc_record(score):
    keys = [
        "model_revision", "status", "soc_feasible", "feasible", "loss_mw",
        "shed_mw", "reactive_shed_mvar", "vmin_pu", "vmax_pu", "slack_p_mw",
        "slack_q_mvar", "connected", "radial", "fixed_topology_soc_validated",
        "nonlinear_ac_validated", "engineering_validated", "diagnostics",
        "nonlinear_ac", "qubo",
    ]
    return _jsonable({key: score.get(key) for key in keys})


def _qubo_record(meta):
    upper = np.triu(np.asarray(meta["Q"], dtype=float), 1)
    return {
        "n_binary_variables": int(meta.get("n_binary_variables", meta["n_qubits"])),
        "standard_qaoa_qubits": int(meta["n_qubits"]),
        "n_qubits": int(meta["n_qubits"]),  # legacy-compatible alias
        "objective_convention": _jsonable(
            meta.get("notation_and_objective_convention", {})
        ),
        "target_closed_switches": int(meta["K_target"]),
        "constant": float(meta.get("constant", 0.0)),
        "variable_order_branch_indices": [
            int(value) for value in meta["variable_order_branch_indices"]
        ],
        "linear_coefficients": _jsonable(np.asarray(meta["linear"], dtype=float)),
        "upper_triangular_quadratic_coefficients": _jsonable(upper),
        "offdiagonal_union_nonzero": int(meta["n_offdiag"]),
        "components": _jsonable(meta["component_stats"]),
        "topology_encoding": _jsonable(meta["topology_encoding"]),
        "counting_note": (
            "Component counts overlap: a pair can receive coefficients from more "
            "than one penalty. The union count is the nonzero count after summation."
        ),
    }


def _trial(seed, result, score, fopt, net=None, meta=None, faulted=None):
    metadata = {
        key: value
        for key, value in result.items()
        if key not in {"x", "fval", "time_s", "method", "n_qubits"}
    }
    objective_gap = float(result["fval"] - fopt)
    trial = {
        "seed": seed,
        "returned_bits": _jsonable(result["x"]),  # legacy-compatible alias
        "returned_bits_variable_order": _jsonable(result["x"]),
        "objective": float(result["fval"]),
        "objective_gap": objective_gap,
        "approximation_ratio": approx_ratio(result["fval"], fopt),
        "reached_exact_qubo_optimum": bool(abs(objective_gap) <= 1e-6),
        "returned_objective_equals_f_Q_star": bool(
            abs(objective_gap) <= 1e-6
        ),
        "time_s": float(result["time_s"]),
        "fixed_topology_soc": _soc_record(score),
        "solver_metadata": _jsonable(metadata),
    }
    if net is not None and meta is not None:
        from qubo_builder import qubo_energy, z_to_dict
        from radiality import project_to_spanning_tree, topology_status

        raw_bits = np.asarray(result["x"], dtype=int)
        raw_z = z_to_dict(raw_bits, meta)
        raw_topology = topology_status(net, raw_z, faulted)
        projection = project_to_spanning_tree(net, raw_z, faulted)
        projected_z = projection["z"]
        order = meta["variable_order_branch_indices"]
        projected_bits = np.asarray([projected_z[index] for index in order], dtype=int)
        projected_objective = qubo_energy(projected_bits, meta)
        projected_score = solvers.score_config(
            net, projected_bits, meta, faulted=faulted
        )
        trial["raw_candidate"] = {
            "bits_variable_order": _jsonable(raw_bits),
            "qubo_objective": float(result["fval"]),
            "topology": _jsonable(raw_topology),
            "fixed_topology_validation": _soc_record(score),
        }
        trial["projection"] = {
            "required": bool(projection.get("n_switch_changes", 0)),
            "success": bool(projection["success"]),
            "reason": projection.get("reason"),
            "opened_switches": projection.get("opened_switches", []),
            "closed_switches": projection.get("closed_switches", []),
            "n_switch_changes": int(projection.get("n_switch_changes", 0)),
            "projected_bits_variable_order": _jsonable(projected_bits),
            "projected_qubo_objective": float(projected_objective),
            "projected_objective_change": float(
                projected_objective - result["fval"]
            ),
            "projected_topology": _jsonable(
                topology_status(net, projected_z, faulted)
            ),
            "projected_fixed_topology_validation": _soc_record(projected_score),
        }
    return trial


def _method_record(name, method_qubits, trials):
    from statistics_report import summarize_trials

    ratios = [trial["approximation_ratio"] for trial in trials]
    times = [trial["time_s"] for trial in trials]
    hits = [trial["reached_exact_qubo_optimum"] for trial in trials]
    representative = min(trials, key=lambda trial: (trial["objective"], trial["seed"]))
    hit_fraction = float(np.mean(hits))
    return {
        "method": name,
        "method_qubits": int(method_qubits),
        "optimizer_runs": len(trials),
        "approximation_ratio_mean": float(np.mean(ratios)),
        "approximation_ratio_std": float(np.std(ratios)),
        "exact_optimum_hit_fraction": hit_fraction,  # compatibility alias
        "optimizer_run_exact_qubo_hit_fraction": hit_fraction,
        "hit_fraction_definition": (
            "fraction of independent optimizer runs whose returned objective "
            "reached the exact QUBO optimum"
        ),
        "time_mean_s": float(np.mean(times)),
        "offset_invariant_statistics": summarize_trials(trials),
        "representative_fixed_topology_soc": {
            **representative["fixed_topology_soc"],
            "scope": "best returned QUBO objective; tie broken by lowest seed",
        },
        "trials": trials,
    }


def _save(artifact):
    RESULTS_PATH.parent.mkdir(exist_ok=True)
    RESULTS_PATH.write_text(json.dumps(artifact, indent=2, allow_nan=False) + "\n")


def _save_post_contingency(artifact):
    POST_CONTINGENCY_RESULTS_PATH.parent.mkdir(exist_ok=True)
    POST_CONTINGENCY_RESULTS_PATH.write_text(
        json.dumps(_jsonable(artifact), indent=2, allow_nan=False) + "\n"
    )


def run_benchmark(
    sizes=(4, 6, 8, 10, 12),
    seeds=(42, 7, 123),
    reps_list=(1, 2),
    shots=1024,
    maxiter=50,
    ground_truth_max_size=10,
):
    from study_protocol import build_protocol, validate_protocol

    protocol = build_protocol()
    validate_protocol(protocol)
    artifact = {
        "schema_version": 2,
        "artifact_id": "koshi-benchmark-v2",
        "status": "generated from retained per-run results",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "provenance": {
            "source_commit": _git_commit(),
            "generator": "benchmark.py",
            "package_versions": _versions(),
        },
        "benchmark_configuration": {
            "sizes": list(sizes),
            "qaoa_qrao_and_sa_seeds": list(seeds),
            "qaoa_depths": list(reps_list),
            "shots": shots,
            "optimizer_max_iterations": maxiter,
            "ground_truth_max_size": ground_truth_max_size,
            "contingency": None,
            "interpretation": "legacy-compatible base-case sweep; not post-contingency",
        },
        "study_protocol": {
            "protocol_revision": protocol["protocol_revision"],
            "protocol_sha256": protocol["protocol_sha256"],
            "prospective_results_status": "not generated by legacy sweep",
        },
        "continuous_model_evidence": {
            "current_code_revision": power_model.MODEL_REVISION,
            "numeric_results_model_revision": power_model.MODEL_REVISION,
            "status": "current; regenerated by benchmark.py",
        },
        "radiality_model_evidence": {
            "current_code_revision": "exact-radiality-v1",
            "historical_qubo_revision": "heuristic-topology-qubo-v1",
            "status": (
                "exact topology audit is current; QAOA/QRAO/SA still optimize "
                "the explicitly heuristic topology-coupled QUBO"
            ),
        },
        "hardware_model_evidence": {
            "current_code_revision": "hardware-evidence-v2",
            "numeric_result_status": "not generated by benchmark.py",
            "required_output": (
                "results/hardware_YYYYMMDDTHHMMSSZ/hardware_results.json"
            ),
            "manuscript_table_output": "generated/hardware_evidence_tables.tex",
        },
        "instances": [],
        "excluded_evidence": {
            "admm": {
                "status": "separate evidence artifact required",
                "reason": "Generated by make_admm_figure.py, not this benchmark.",
            },
            "hardware": {
                "status": "separate raw evidence artifact required",
                "reason": "Generated by phase3_hardware.py, not this benchmark.",
                "required_schema": "hardware-evidence-v2",
            },
            "qrao_ablation": {
                "status": "not run by this benchmark",
                "reason": "No ablation is claimed unless a dedicated result is archived.",
            },
            "qiskit_admm_optimizer": {
                "status": "not part of benchmark comparison",
                "reason": "The library surrogate is not the nonlinear fixed-topology SOC model.",
            },
        },
    }

    for n in sizes:
        net = scaled_network(n)
        qp, meta = build_reconfig_qubo(net)
        from artifact_pipeline import _radiality_audit

        radiality_audit = _radiality_audit(n)
        exact = solvers.solve_exact_qubo(qp)
        fopt = exact["fval"]
        exact_score = solvers.score_config(net, exact["x"], meta)
        best_connected = None
        best_radial = None
        search_meta = None
        if n <= ground_truth_max_size:
            ground = solvers.brute_force_soc(net, meta, max_eval=4000)
            best_connected = _finite(ground["best_connected"].get("loss_mw"))
            best_radial = _finite(ground["best_radial"].get("loss_mw"))
            search_meta = {
                "evaluated_connected_configurations": int(ground["n_eval"]),
                "time_s": float(ground["time_s"]),
            }

        methods = []
        for kind, reps in [("noiseless", r) for r in reps_list] + [("noisy", 1)]:
            trials = []
            for seed in seeds:
                result = solvers.solve_qaoa(
                    qp, reps=reps, kind=kind, shots=shots, maxiter=maxiter, seed=seed
                )
                score = solvers.score_config(net, result["x"], meta)
                trials.append(_trial(seed, result, score, fopt, net, meta))
            methods.append(_method_record(f"QAOA p{reps} {kind}", meta["n_qubits"], trials))

        qrao_trials = []
        for seed in seeds:
            result = solvers.solve_qrao(
                qp, max_vars_per_qubit=3, maxiter=maxiter, shots=shots, seed=seed
            )
            score = solvers.score_config(net, result["x"], meta)
            qrao_trials.append(_trial(seed, result, score, fopt, net, meta))
        methods.append(_method_record("QRAO 3v", result["n_qubits"], qrao_trials))

        sa_trials = []
        for seed in seeds:
            result = solvers.solve_sa_qubo(meta, iters=300, seed=seed)
            score = solvers.score_config(net, result["x"], meta)
            sa_trials.append(_trial(seed, result, score, fopt, net, meta))
        methods.append(_method_record("SA", 0, sa_trials))

        instance = {
            "n": int(n),
            "qubo": _qubo_record(meta),
            "radiality_audit": radiality_audit,
            "exact_qubo": {
                "objective": float(exact["fval"]),
                "objective_symbol": "f_Q_star",
                "time_s": float(exact["time_s"]),
                "one_minimizer_bits_variable_order": _jsonable(exact["x"]),
                "returned_bits": _jsonable(exact["x"]),  # compatibility alias
                "fixed_topology_soc": _soc_record(exact_score),
            },
            "best_connected_fixed_topology_soc": {
                "loss_mw": best_connected,
                "best_radial_loss_mw": best_radial,
                "search_type": "brute-force enumeration" if search_meta else "not run",
                "search_metadata": search_meta,
            },
            "methods": methods,
        }
        artifact["instances"].append(instance)
        _save(artifact)
        print(
            f"n={n}: exact={fopt:.3f}, exact connected="
            f"{exact_score.get('connected')}, methods={len(methods)}"
        )
    return artifact


def run_post_contingency_study():
    """Run the predeclared full-decision-set N-1 study.

    This is intentionally separate from ``results/benchmark.json`` so a partial
    or failed prospective run cannot overwrite the frozen legacy artifact.
    """
    from radiality import (
        solve_exact_enumeration,
        solve_exact_radial_qubo,
        solve_spanning_tree_milp,
    )
    from study_protocol import build_protocol, validate_protocol

    protocol = build_protocol()
    validate_protocol(protocol)
    primary = protocol["prospective_primary_protocol"]
    checkpoint = None
    if POST_CONTINGENCY_RESULTS_PATH.exists():
        try:
            candidate = json.loads(POST_CONTINGENCY_RESULTS_PATH.read_text())
            if candidate.get("protocol_sha256") == protocol["protocol_sha256"]:
                checkpoint = candidate
        except (OSError, ValueError, TypeError):
            checkpoint = None
    faulted = [primary["contingency"]["forced_open_branch_index"]]
    seeds = primary["qaoa"]["seeds"]
    net = build_full_network()
    qp, meta = build_reconfig_qubo(
        net,
        faulted=faulted,
        **{
            key: primary["qubo_parameters"][key]
            for key in ("lambda_card", "lambda_cycle", "lambda_iso", "loss_bias")
        },
    )
    exact = solvers.solve_exact_qubo(qp)
    exact_enumerated = solve_exact_enumeration(meta)
    fopt = exact["fval"]
    exact_score = solvers.score_config(net, exact["x"], meta, faulted=faulted)
    hard_radial = solve_exact_radial_qubo(net, meta, faulted=faulted)
    spanning_tree = solve_spanning_tree_milp(net, faulted=faulted)
    run_commit = _git_commit()
    artifact = {
        "schema_version": 1,
        "artifact_id": "koshi-post-contingency-v1",
        "status": "running",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "protocol_revision": protocol["protocol_revision"],
        "protocol_sha256": protocol["protocol_sha256"],
        "provenance": {
            "source_commit": run_commit,
            "package_versions": _versions(),
            "generator": "benchmark.run_post_contingency_study",
        },
        "scenario": primary["contingency"],
        "faulted_branches": faulted,
        "variable_order": [
            {
                "position": position,
                "branch_index": branch_index,
                "name": net.branches[branch_index].name,
            }
            for position, branch_index in enumerate(meta["switch_branches"])
        ],
        "qubo": _qubo_record(meta),
        "exact_qubo": {
            "objective": float(fopt),
            "objective_symbol": "f_Q_star",
            "one_minimizer_bits_variable_order": _jsonable(exact["x"]),
            "all_minimizers_bits_variable_order": _jsonable(
                exact_enumerated["all_minimizers_variable_order"]
            ),
            "minimizer_count": int(exact_enumerated["minimizer_count"]),
            "returned_bits": _jsonable(exact["x"]),  # compatibility alias
            "time_s": float(exact["time_s"]),
            "fixed_topology_validation": _soc_record(exact_score),
        },
        "hard_radial_references": {
            "exact_radial_qubo_enumeration": _jsonable(hard_radial),
            "single_commodity_flow_milp": _jsonable(spanning_tree),
        },
        "methods": [],
        "sensitivity_analysis": {
            "status": "not run by primary solver loop",
            "required_design": primary["sensitivity_analysis"],
        },
    }
    expected_method_names = [
        *[f"QAOA p{reps} noiseless" for reps in primary["qaoa"]["depths"]],
        "QRAO 3v",
        "SA",
    ]
    if checkpoint is not None:
        checkpoint_commit = checkpoint.get("provenance", {}).get("source_commit")
        reusable = {}
        for method in checkpoint.get("methods", []):
            name = method.get("method")
            recorded_seeds = [trial.get("seed") for trial in method.get("trials", [])]
            if (
                name in expected_method_names
                and len(recorded_seeds) == len(seeds)
                and sorted(recorded_seeds) == sorted(seeds)
                and len(recorded_seeds) == len(set(recorded_seeds))
            ):
                method["source_commit"] = method.get(
                    "source_commit", checkpoint_commit
                )
                reusable[name] = method
        artifact["methods"] = [
            reusable[name] for name in expected_method_names if name in reusable
        ]
        if artifact["methods"]:
            artifact["provenance"]["resumed_from_source_commit"] = checkpoint_commit
            artifact["provenance"]["reused_method_records"] = [
                method["method"] for method in artifact["methods"]
            ]
        partial = checkpoint.get("in_progress_quantum_trials", {})
        partial_seeds = [
            trial.get("seed") for trial in partial.get("trials", [])
        ]
        if (
            partial.get("method") in expected_method_names
            and set(partial_seeds).issubset(set(seeds))
            and len(partial_seeds) == len(set(partial_seeds))
        ):
            artifact["in_progress_quantum_trials"] = partial
    _save_post_contingency(artifact)

    qaoa = primary["qaoa"]
    for reps in qaoa["depths"]:
        method_name = f"QAOA p{reps} noiseless"
        if any(method["method"] == method_name for method in artifact["methods"]):
            continue
        tasks = [
            ("qaoa", reps, seed, primary, fopt)
            for seed in seeds
        ]
        with ProcessPoolExecutor(
            max_workers=primary["execution"]["parallel_workers"],
            max_tasks_per_child=1,
        ) as pool:
            worker_results = list(pool.map(_prospective_quantum_trial, tasks))
        trials = [trial for trial, _ in worker_results]
        record = _method_record(method_name, meta["n_qubits"], trials)
        record["source_commit"] = run_commit
        artifact["methods"].append(record)
        _save_post_contingency(artifact)

    if not any(method["method"] == "QRAO 3v" for method in artifact["methods"]):
        partial = artifact.get("in_progress_quantum_trials", {})
        if partial.get("method") == "QRAO 3v":
            qrao_trials = list(partial.get("trials", []))
            qrao_qubits = partial.get("method_qubits")
            source_commits = set(partial.get("source_commits", []))
        else:
            qrao_trials = []
            qrao_qubits = None
            source_commits = set()
        completed_seeds = {trial["seed"] for trial in qrao_trials}
        tasks = [
            ("qrao", 0, seed, primary, fopt)
            for seed in seeds
            if seed not in completed_seeds
        ]
        qrao_workers = primary["execution"]["parallel_workers"]
        with ProcessPoolExecutor(
            max_workers=qrao_workers,
            max_tasks_per_child=1,
        ) as pool:
            for trial, trial_qubits in pool.map(
                _prospective_quantum_trial, tasks
            ):
                qrao_trials.append(trial)
                qrao_qubits = trial_qubits
                source_commits.add(run_commit)
                artifact["in_progress_quantum_trials"] = {
                    "method": "QRAO 3v",
                    "method_qubits": qrao_qubits,
                    "trials": qrao_trials,
                    "source_commits": sorted(source_commits),
                }
                _save_post_contingency(artifact)
        qrao_trials.sort(key=lambda trial: seeds.index(trial["seed"]))
        record = _method_record("QRAO 3v", qrao_qubits, qrao_trials)
        record["source_commit"] = run_commit
        record["source_commits"] = sorted(source_commits)
        record["execution"] = {
            "parallel_workers": qrao_workers,
            "memory_control": (
                "deterministic MagicRounding circuit batches; one trial per "
                "worker process"
            ),
        }
        artifact["methods"].append(record)
        artifact.pop("in_progress_quantum_trials", None)
        _save_post_contingency(artifact)

    sa_config = primary["simulated_annealing"]
    if not any(method["method"] == "SA" for method in artifact["methods"]):
        sa_trials = []
        for seed in seeds:
            result = solvers.solve_sa_qubo(
                meta,
                iters=sa_config["iterations"],
                T0=sa_config["initial_temperature"],
                cooling=sa_config["cooling_factor"],
                seed=seed,
            )
            score = solvers.score_config(net, result["x"], meta, faulted=faulted)
            sa_trials.append(
                _trial(seed, result, score, fopt, net, meta, faulted=faulted)
            )
        record = _method_record("SA", 0, sa_trials)
        record["source_commit"] = run_commit
